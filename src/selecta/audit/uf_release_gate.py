"""Unified finish (UF) charter, dependency graph and release gate (UF-0366-07, -08, UF-0389-08).

- `dependency_graph` proposes the UF delivery order from the code-status JSON: phase by phase,
  correctness and comprehension (P0) ahead of P1, and animation or pixel-only polish last in each
  phase. It is a proposal until a named owner approves it in charter-approval.json.
- `charter_problems` checks the charter approval record (named owner, date, rationale, any
  rejected decisions with reasons).
- `gate` is the release dry run: zero unresolved P0 tasks, a decision for every open P1 task, a
  rollback plan that exists, a named owner, an independent GO sign-off by someone else, and every
  person-evidence log complete. Today it answers NO-GO and lists why; nothing here fills a record.

    python -m selecta.audit.uf_release_gate            # dry run, prints GO or NO-GO
    python -m selecta.audit.uf_release_gate --write    # regenerate the dependency graph page
    python -m selecta.audit.uf_release_gate --check    # exit 1 when that page is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from selecta.audit import uf_human_logs

STATUS = Path("docs/adr/selecta-unified-finish-code-status.json")
LOGS = Path("docs/verification/uf")
GRAPH = Path("docs/adr/completion/uf-dependency-graph.md")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
# ADRs whose remaining work is animation, motion or pixel-level polish rather than correctness
POLISH = {369, 375}


def _named(value: object) -> bool:
    return isinstance(value, str) and value.strip(" -") != ""


def _risk(adr: dict) -> int:
    """0 = correctness/comprehension P0, 1 = P1, 2 = animation or pixel-only polish."""
    if adr["number"] in POLISH:
        return 2
    return 0 if adr["priority"] == "P0" else 1


def _phase(adr: dict) -> int:
    return int(str(adr["phase"])[:2])


def dependency_graph(status: dict) -> list[dict]:
    """The proposed order: each ADR depends on every ADR of an earlier phase."""
    adrs = sorted(status["adrs"], key=lambda a: (_phase(a), _risk(a), a["number"]))
    order = []
    for adr in adrs:
        before = sorted(a["number"] for a in adrs if _phase(a) < _phase(adr))
        order.append(
            {
                "adr": adr["number"],
                "title": adr["title"],
                "phase": adr["phase"],
                "phase_number": _phase(adr),
                "priority": adr["priority"],
                "risk": ("correctness", "P1", "polish")[_risk(adr)],
                "after_phases_of": before,
            }
        )
    return order


def order_problems(order: list[dict]) -> list[str]:
    """No polish ADR comes before a correctness ADR of the same or an earlier phase."""
    problems = []
    for index, item in enumerate(order):
        if item["risk"] != "polish":
            continue
        for later in order[index + 1 :]:
            if later["risk"] == "correctness" and later["phase_number"] <= item["phase_number"]:
                problems.append(f"ADR-0{item['adr']} polish precedes ADR-0{later['adr']}")
    return problems


def render_graph(order: list[dict]) -> str:
    lines = [
        "# Unified finish dependency graph (proposed, not owner-approved)",
        "",
        "Generated by `python -m selecta.audit.uf_release_gate --write` from",
        "`docs/adr/selecta-unified-finish-code-status.json` for UF-0366-07. Each ADR waits for",
        "every ADR of an earlier phase; inside a phase, correctness and comprehension (P0) go",
        "first, then P1, then animation and pixel-only polish (ADR-0369, ADR-0375). It stays a",
        "proposal until a",
        "named owner approves it in `docs/verification/uf/charter-approval.json`.",
        "",
        "| Step | ADR | Phase | Priority | Risk class | Waits for phases of |",
        "|---|---|---|---|---|---|",
    ]
    for step, item in enumerate(order, 1):
        waits = ", ".join(f"0{n}" for n in item["after_phases_of"]) or "-"
        lines.append(
            f"| {step} | ADR-0{item['adr']} {item['title']} | {item['phase']} | "
            f"{item['priority']} | {item['risk']} | {waits} |"
        )
    return "\n".join(lines) + "\n"


def charter_problems(record: dict) -> list[str]:
    """UF-0366-08 (and the approval half of -07): what the charter approval record still needs."""
    problems = []
    if not _named(record.get("owner")):
        problems.append("charter: no named owner")
    if not DATE.match(str(record.get("date", ""))):
        problems.append("charter: no approval date")
    if not _named(record.get("rationale")):
        problems.append("charter: no rationale")
    if not isinstance(record.get("rejected_decisions"), list):
        problems.append("charter: rejected_decisions must be a list (empty when none)")
    for item in record.get("rejected_decisions") or []:
        if not (_named(item.get("decision")) and _named(item.get("reason"))):
            problems.append("charter: each rejected decision needs the decision and a reason")
    if not _named(record.get("dependency_graph_approved_by")):
        problems.append("charter: dependency graph not approved by a named owner (UF-0366-07)")
    return problems


def unresolved(status: dict, priority: str) -> list[str]:
    """Tasks of that priority not yet independently verified."""
    return [
        task["id"]
        for adr in status["adrs"]
        if adr["priority"] == priority
        for task in adr["tasks"]
        if not task.get("independently_verified")
    ]


def gate(root: Path, status: dict, verdict: dict, charter: dict) -> list[str]:
    """UF-0389-08: every reason the release is NO-GO (empty means GO)."""
    problems = [f"unresolved P0 task {task}" for task in unresolved(status, "P0")]
    decided = {
        d.get("task")
        for d in verdict.get("p1_decisions", [])
        if d.get("decision") in ("accept", "defer") and _named(d.get("rationale"))
    }
    problems += [
        f"no recorded decision for open P1 task {task}"
        for task in unresolved(status, "P1")
        if task not in decided
    ]
    rollback = str(verdict.get("rollback", ""))
    if not rollback or not (root / rollback).is_file():
        problems.append("no rollback plan file named in the verdict")
    owner = verdict.get("owner")
    if not _named(owner):
        problems.append("no named release owner")
    sign = verdict.get("go_signoff") or {}
    if not (_named(sign.get("reviewer")) and DATE.match(str(sign.get("date", "")))):
        problems.append("no independent GO sign-off with reviewer and date")
    elif sign.get("reviewer") == owner:
        problems.append("the GO sign-off must come from someone other than the owner")
    elif sign.get("verdict") != "GO":
        problems.append(f"sign-off verdict is {sign.get('verdict')!r}, not GO")
    problems += charter_problems(charter)
    for name, open_items in uf_human_logs.all_status(root).items():
        if open_items:
            problems.append(f"person-evidence log {name} incomplete ({len(open_items)} open)")
    return problems


def _json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[3]
    status = _json(root / STATUS)
    text = render_graph(dependency_graph(status))
    if args.write:
        (root / GRAPH).write_text(text, encoding="utf-8")
        print(f"wrote {GRAPH}")
        return 0
    if args.check:
        same = (root / GRAPH).is_file() and (root / GRAPH).read_text(encoding="utf-8") == text
        print("dependency graph up to date" if same else f"{GRAPH} is out of date")
        return 0 if same else 1
    problems = gate(
        root,
        status,
        _json(root / LOGS / "release-verdict.json"),
        _json(root / LOGS / "charter-approval.json"),
    )
    print("GO" if not problems else f"NO-GO: {len(problems)} reason(s)")
    for problem in problems[:40]:
        print(f"  - {problem}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
