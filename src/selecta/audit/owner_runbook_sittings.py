"""The sittings of the owner verification runbook: what each one covers and its script.

SITTINGS is in the order the owner should do them. CLASSIFY_ORDER is the order the classifier
tries them: a task goes to the first sitting whose words match its title and "Needs a person"
text, so the narrow sittings (legal, staging, screen reader, devices, listening) come before the
broad ones (study, visual review), and the sign-off pass catches everything else. OVERRIDES pins
a task to a sitting when the words mislead; it was built by reviewing every task by hand on
2026-11-12, and new tasks fall back to the word rules.
"""

