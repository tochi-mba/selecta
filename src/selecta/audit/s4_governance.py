"""Selecta 4.0 governance evidence that a script can gather (ADR-0089 and ADR-0113).

Three generated documents, each the automatable half of a task that a person still signs:

- `docs/adr/completion/s4-api-inventory.md` (S4-0089-02): every mounted `/api/` route with its
  method, side effect, owning feature flag, owning module, request schema and what it does, read
  from the live FastAPI app and the flag registry. Page routes, tabs, overlays and settings are in
  `docs/adr/mp-0272-surface-inventory.json`, guarded by `web/src/shell/mpSurfaceInventory.test.ts`.
- `docs/adr/completion/s4-pr28-boundary.md` (S4-0089-07): the changed-path audit of the PR #28
  merge, one row per path with its kind and the PR commits that touched it, so the owner can give
  each runtime path a disposition.
- `docs/verification/s4-release-report.md` (S4-0089-01, -10, S4-0113-01, -09, -10): an exact-head
  release report scaffold filled from git, the checklist, CI runs and a rollback log. Its computed
  verdict is NO-GO until every gate has proof; the owner's GO/NO-GO line is left blank.

    python -m selecta.audit.s4_governance --write [--ci] [--rollback-log FILE]
    python -m selecta.audit.s4_governance --check   # exit 1 when an inventory is out of date

`--ci` asks `gh run list` for the head's runs (network). Without it the CI section says so.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
API_DOC = "docs/adr/completion/s4-api-inventory.md"
BOUNDARY_DOC = "docs/adr/completion/s4-pr28-boundary.md"
REPORT_DOC = "docs/verification/s4-release-report.md"
CHECKLIST = "docs/adr/selecta-4-implementation-checklist.md"
BASELINE = "9b663f9f10212619f27ce67ce82f602347065cbd"
PR28_MERGE = "681208046d5efb8fe6a2f55622f3ebfc03869d48"
READS = {"GET", "HEAD", "OPTIONS"}
GENERATED = "Generated by `python -m selecta.audit.s4_governance --write`; do not edit by hand."


def _cell(text: object) -> str:
    return str(text).replace("\u2014", "-").replace("|", "\\|").replace("\n", " ").strip()


# ---------------------------------------------------------------- S4-0089-02: API inventory


@dataclass(frozen=True)
class ApiRow:
    method: str
    path: str
    effect: str
    flag: str
    module: str
    body: str
    does: str


def api_rows(app, owners: dict[str, str]) -> list[ApiRow]:
    """One row per method and `/api/` path the app mounts, owner from the flag registry."""
    from fastapi.routing import APIRoute

    rows: set[ApiRow] = set()
    for route in app.router.routes:
        if not isinstance(route, APIRoute) or not route.path.startswith("/api/"):
            continue
        body = getattr(getattr(route, "body_field", None), "type_", None)
        doc = (route.endpoint.__doc__ or "").strip().split("\n\n")[0]
        for method in sorted(route.methods or ()):
            if method == "HEAD" and "GET" in (route.methods or ()):
                continue
            key = f"{'GET' if method == 'HEAD' else method} {route.path}"
            rows.add(
                ApiRow(
                    method=method,
                    path=route.path,
                    effect="reads" if method in READS else "changes state",
                    flag=owners.get(key, "UNOWNED"),
                    module=route.endpoint.__module__.removeprefix("selecta."),
                    body=getattr(body, "__name__", "") if body is not None else "",
                    does=" ".join(doc.split()),
                )
            )
    return sorted(rows, key=lambda row: (row.path, row.method))


def live_api_rows() -> list[ApiRow]:
    from selecta import flags
    from selecta.api import create_app
    from selecta.config import Settings

    with tempfile.TemporaryDirectory(prefix="selecta-s4-inventory-") as folder:
        home = Path(folder)
        app = create_app(Settings(home), home / "no-web", prepare_links=False)
        return api_rows(app, flags.route_owners())


def api_markdown(rows: list[ApiRow]) -> str:
    writes = sum(1 for row in rows if row.effect != "reads")
    unowned = [f"{row.method} {row.path}" for row in rows if row.flag == "UNOWNED"]
    lines = [
        "# Selecta 4.0 API inventory (S4-0089-02)",
        "",
        GENERATED,
        "",
        f"{len(rows)} method and path pairs: {len(rows) - writes} read, {writes} change state. "
        f"{len(unowned)} have no feature-flag owner. Owners come from `src/selecta/flags/*.json`; "
        "routes, tabs, overlays and settings of the site are in "
        "[mp-0272-surface-inventory.json](../mp-0272-surface-inventory.json).",
        "",
        "| Method | Path | Side effect | Owning flag | Module | Request schema | What it does |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row.method} | `{row.path}` | {row.effect} | `{row.flag}` | {_cell(row.module)} "
            f"| {_cell(row.body) or '-'} | {_cell(row.does) or '-'} |"
        )
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- S4-0089-07: PR #28 boundary


def _git(*args: str, root: Path = ROOT) -> str:
    done = subprocess.run(
        ["git", *args], cwd=root, capture_output=True, text=True, check=False, encoding="utf-8"
    )
    if done.returncode:
        raise RuntimeError(done.stderr.strip() or f"git {' '.join(args)} failed")
    return done.stdout


def has_commit(sha: str, root: Path = ROOT) -> bool:
    try:
        _git("cat-file", "-e", f"{sha}^{{commit}}", root=root)
        return True
    except RuntimeError:
        return False


def path_kind(path: str) -> str:
    if path.startswith("docs/") or path.endswith(".md"):
        return "docs"
    if path.startswith(("tests/", "web/e2e/")) or ".test." in path:
        return "test"
    if path.startswith((".github/", "scripts/")):
        return "ci"
    return "runtime"


@dataclass(frozen=True)
class BoundaryRow:
    path: str
    kind: str
    commits: tuple[str, ...]

    @property
    def disposition(self) -> str:
        if self.kind == "docs":
            return "inside the docs-only boundary"
        return "outside the boundary: owner disposition needed"


def boundary_rows(merge: str = PR28_MERGE, root: Path = ROOT) -> list[BoundaryRow]:
    paths = _git("diff", "--name-only", f"{merge}^1", merge, root=root).split()
    rows = []
    for path in sorted(paths):
        log = _git("log", "--format=%h %s", f"{merge}^1..{merge}^2", "--", path, root=root)
        rows.append(BoundaryRow(path, path_kind(path), tuple(log.strip().splitlines())))
    return rows


def boundary_markdown(rows: list[BoundaryRow], merge: str = PR28_MERGE) -> str:
    kinds = {
        kind: sum(1 for row in rows if row.kind == kind) for kind in sorted({r.kind for r in rows})
    }
    outside = [row for row in rows if row.kind != "docs"]
    lines = [
        "# PR #28 changed-path audit (S4-0089-07)",
        "",
        GENERATED,
        "",
        f"`git diff --name-only {merge[:7]}^1 {merge[:7]}` lists {len(rows)} paths ("
        + ", ".join(f"{count} {kind}" for kind, count in kinds.items())
        + "). ADR-0089 required this PR to change documentation only, so "
        f"{len(outside)} paths fall outside the boundary. The commits column lists the PR "
        f"branch commits (`{merge[:7]}^1..{merge[:7]}^2`) that touched each path.",
        "",
        "| Path | Kind | PR commits that touched it | Disposition | Owner decision |",
        "|---|---|---|---|---|",
    ]
    for row in outside + [row for row in rows if row.kind == "docs"]:
        commits = "; ".join(_cell(commit) for commit in row.commits) or "-"
        lines.append(f"| `{row.path}` | {row.kind} | {commits} | {row.disposition} |  |")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- S4-0113-06: dependencies


def declared_dependencies(pyproject: str, package_json: str) -> dict[str, str]:
    """`python:<name>` / `web:<name>` to the declared spec, from every dependency list."""
    import tomllib

    out: dict[str, str] = {}
    project = tomllib.loads(pyproject) if pyproject else {}
    lists = [project.get("project", {}).get("dependencies", [])]
    lists += list(project.get("project", {}).get("optional-dependencies", {}).values())
    lists += list(project.get("dependency-groups", {}).values())
    for specs in lists:
        for spec in specs:
            if isinstance(spec, str):
                name = re.split(r"[<>=!~\[ ;]", spec, maxsplit=1)[0].lower()
                out[f"python:{name}"] = spec
    package = json.loads(package_json) if package_json else {}
    for group in ("dependencies", "devDependencies"):
        for name, spec in package.get(group, {}).items():
            out[f"web:{name}"] = spec
    return out


def dependency_changes(before: dict[str, str], after: dict[str, str]) -> list[tuple[str, str, str]]:
    """(name, change, detail) for every added, removed or re-specified dependency."""
    rows = []
    for name in sorted(set(before) | set(after)):
        if name not in before:
            rows.append((name, "added", after[name]))
        elif name not in after:
            rows.append((name, "removed", before[name]))
        elif before[name] != after[name]:
            rows.append((name, "changed", f"{before[name]} -> {after[name]}"))
    return rows


def dependency_rows(root: Path = ROOT, since: str = BASELINE) -> list[tuple[str, str, str]]:
    def show(path: str) -> str:
        try:
            return _git("show", f"{since}:{path}", root=root)
        except RuntimeError:
            return ""

    before = declared_dependencies(show("pyproject.toml"), show("web/package.json"))
    after = declared_dependencies(
        (root / "pyproject.toml").read_text("utf-8"),
        (root / "web" / "package.json").read_text("utf-8"),
    )
    return dependency_changes(before, after)


# ---------------------------------------------------------------- release report


@dataclass
class ReleaseFacts:
    head: str
    branch: str
    main_head: str
    today: str
    merges: list[str]
    counts: dict[str, int]
    verified: int
    total: int
    phases: list[tuple[str, str, int, int]]
    ci_runs: list[dict] | None = None
    rollback: dict | None = None
    open_p0: list[str] = field(default_factory=list)
    dependencies: list[tuple[str, str, str]] | None = None


PHASE = re.compile(r"^### \[(ADR-\d{4}) - ([^\]]+)\]")
PHASE_LINE = re.compile(r"^\*\*Phase:\*\* ([^.]+)\.")


def phases(checklist_text: str) -> list[tuple[str, str, int, int]]:
    """(phase, ADR, implemented, tasks) in checklist order: the staged PR order to approve."""
    out: list[tuple[str, str, int, int]] = []
    adr = None
    for line in checklist_text.splitlines():
        head = PHASE.match(line)
        if head:
            adr = head.group(1)
            continue
        phase = PHASE_LINE.match(line)
        if phase and adr:
            out.append((phase.group(1), adr, 0, 0))
            continue
        if adr and out and out[-1][1] == adr and re.match(r"^- \[[ xX]\] \*\*S4-", line):
            name, which, done, total = out[-1]
            implemented = bool(re.search(r"Implementation:?\**:?\s*\**\s*Implemented", line))
            out[-1] = (name, which, done + implemented, total + 1)
    return out


def parse_rollback_log(text: str, older: str) -> dict:
    lines = [line for line in text.splitlines() if line.strip()]
    exit_code = next(
        (int(m.group(1)) for m in map(re.compile(r"^exit=(\d+)").match, lines) if m), None
    )
    passed = any(line.strip() == "nothing lost" for line in lines) and exit_code in (0, None)
    notes = [
        line for line in lines if line.startswith(("the older checkout", "this checkout again"))
    ]
    return {"older": older, "passed": passed, "exit": exit_code, "notes": notes}


def computed_verdict(facts: ReleaseFacts) -> tuple[str, list[str]]:
    missing = []
    head_runs = [run for run in facts.ci_runs or [] if run.get("headSha") == facts.head]
    if facts.ci_runs is None:
        missing.append("CI runs for the exact head were not fetched")
    elif not head_runs or any(
        run.get("conclusion") not in ("success", "skipped") for run in head_runs
    ):
        missing.append("CI for the exact head is not all green")
    if not facts.rollback or not facts.rollback.get("passed"):
        missing.append("no passing rollback run is attached")
    if facts.open_p0:
        missing.append(f"{len(facts.open_p0)} open P0 defects")
    if facts.verified < facts.total:
        missing.append(
            f"{facts.total - facts.verified} of {facts.total} tasks not independently Verified"
        )
    return ("NO-GO" if missing else "ready for owner GO"), missing


def gather(root: Path = ROOT, *, ci: bool = False, rollback: dict | None = None) -> ReleaseFacts:
    from selecta.audit.checklist_summary import STATES, summarise

    summary = summarise(root / CHECKLIST)
    head = _git("rev-parse", "HEAD", root=root).strip()
    runs = None
    if ci:
        done = subprocess.run(
            [
                "gh",
                "run",
                "list",
                "--commit",
                head,
                "--limit",
                "30",
                "--json",
                "databaseId,headSha,headBranch,conclusion,status,workflowName,url",
            ],
            cwd=root,
            capture_output=True,
            text=True,
            check=False,
            encoding="utf-8",
        )
        runs = json.loads(done.stdout) if done.returncode == 0 and done.stdout.strip() else None
    main_head = _git("rev-parse", "origin/main", root=root).strip()
    merges = (
        _git(
            "log",
            "--merges",
            "--first-parent",
            "--format=%h %s",
            f"{BASELINE}..{main_head}",
            root=root,
        )
        .strip()
        .splitlines()
    )
    return ReleaseFacts(
        head=head,
        branch=_git("rev-parse", "--abbrev-ref", "HEAD", root=root).strip(),
        main_head=main_head,
        today=dt.date.today().isoformat(),
        merges=merges,
        counts={state: summary.count(state) for state in STATES},
        verified=summary.verified,
        total=len(summary.tasks),
        phases=phases((root / CHECKLIST).read_text(encoding="utf-8")),
        ci_runs=runs,
        rollback=rollback,
        dependencies=dependency_rows(root),
    )


def report_markdown(facts: ReleaseFacts) -> str:
    verdict, missing = computed_verdict(facts)
    counts = ", ".join(f"{n} {state}" for state, n in facts.counts.items())
    lines = [
        "# Selecta 4.0 exact-head release report (S4-0113-10)",
        "",
        GENERATED + " Regenerate it for the head being released.",
        "",
        "## Head",
        "",
        f"- **Head:** `{facts.head}` on `{facts.branch}`, generated {facts.today}.",
        f"- **Main head:** `{facts.main_head}`. **Programme baseline:** `{BASELINE}`.",
        f"- **Tasks:** {facts.total} ({counts}); {facts.verified} independently Verified.",
        "",
        "## Computed verdict",
        "",
        f"**{verdict}**" + (" because:" if missing else "."),
        "",
        *[f"- {reason}" for reason in missing],
        "",
        "## Owner verdict (a person fills this in)",
        "",
        "| Field | Value |",
        "|---|---|",
        "| GO or NO-GO |  |",
        "| Release owner |  |",
        "| Accepted P1 risks and their owner |  |",
        "| Date and signature |  |",
        "",
        "## CI for this head",
        "",
    ]
    if facts.ci_runs is None:
        lines.append("Not fetched. Rerun with `--ci` (uses `gh run list --commit <head>`).")
    elif not facts.ci_runs:
        lines.append("No CI runs exist for this head yet.")
    else:
        lines += ["| Workflow | Run | Status | Conclusion |", "|---|---|---|---|"]
        for run in facts.ci_runs:
            lines.append(
                f"| {_cell(run.get('workflowName', ''))} "
                f"| [{run.get('databaseId')}]({run.get('url', '')}) "
                f"| {run.get('status', '')} | {run.get('conclusion') or '-'} |"
            )
    lines += ["", "## Rollback exercise (`tests/rollback_check.py`)", ""]
    if not facts.rollback:
        lines.append(
            "No rollback log attached. Run `python tests/rollback_check.py <older checkout>`."
        )
    else:
        result = "nothing lost" if facts.rollback["passed"] else "FAILED or incomplete"
        lines.append(
            f"Against `{facts.rollback['older']}`: **{result}** (exit {facts.rollback['exit']})."
        )
        lines += [f"- {_cell(note)}" for note in facts.rollback["notes"]]
    lines += [
        "",
        "## Defect register (S4-0113-09)",
        "",
        "P0 stops the release; P1 needs a named owner's accepted risk; P2 needs a disposition "
        "([release gates](../adr/selecta-4-release-gates.md)). The repository has no P0/P1/P2 "
        "issue labels yet, so the register below is filled by a person.",
        "",
        "| Severity | Defect | Reproduction | Disposition | Owner |",
        "|---|---|---|---|---|",
        *[f"| P0 | {_cell(item)} |  | open |  |" for item in facts.open_p0],
        "|  |  |  |  |  |",
        "",
        "## Staged order by phase (S4-0089-10)",
        "",
        "| Phase | ADR | Implemented | Tasks |",
        "|---|---|---|---|",
        *[f"| {phase} | {adr} | {done} | {total} |" for phase, adr, done, total in facts.phases],
        "",
        f"## Merged to main since the baseline ({len(facts.merges)})",
        "",
        *[f"- {_cell(merge)}" for merge in facts.merges],
    ]
    if facts.dependencies is not None:
        lines += [
            "",
            f"## Dependency changes since the baseline (S4-0113-06, {len(facts.dependencies)})",
            "",
            "Declared in `pyproject.toml` and `web/package.json`; each needs an owner review for "
            "engine, data, network and security impact.",
            "",
            "| Dependency | Change | Spec | Reviewed by |",
            "|---|---|---|---|",
            *[f"| `{n}` | {c} | `{_cell(d)}` |  |" for n, c, d in facts.dependencies],
        ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- command line


def expected(root: Path = ROOT) -> dict[str, str]:
    docs = {API_DOC: api_markdown(live_api_rows())}
    if has_commit(PR28_MERGE, root):
        docs[BOUNDARY_DOC] = boundary_markdown(boundary_rows(root=root))
    return docs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--ci", action="store_true", help="fetch CI runs for the head with gh")
    parser.add_argument("--rollback-log", type=Path, help="output of tests/rollback_check.py")
    parser.add_argument("--rollback-older", default="older checkout", help="what it ran against")
    args = parser.parse_args(argv)
    docs = expected(ROOT)
    if args.check:
        stale = [
            name
            for name, text in docs.items()
            if not (ROOT / name).is_file() or (ROOT / name).read_text("utf-8") != text
        ]
        for name in stale:
            print(f"stale: {name} (run python -m selecta.audit.s4_governance --write)")
        return 1 if stale else 0
    rollback = None
    if args.rollback_log:
        rollback = parse_rollback_log(args.rollback_log.read_text("utf-8"), args.rollback_older)
    docs[REPORT_DOC] = report_markdown(gather(ROOT, ci=args.ci, rollback=rollback))
    for name, text in docs.items():
        (ROOT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
